/**
 * Добавляет base из astro.config.mjs к корневому пути (href/src, начинающиеся с "/").
 * Нужно для превью на GitHub Pages (сайт живёт под /remont-yaroslavl76/) — в боевой сборке
 * на собственном домене base пустой, и функция ничего не меняет.
 */
export function withBase(path: string): string {
	const base = import.meta.env.BASE_URL.replace(/\/$/, "");
	if (path === "/") return `${base}/`;
	return `${base}${path}`;
}

